CREATE TABLE company (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, legal_name VARCHAR(200) NOT NULL
);
CREATE TABLE account (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('CUSTOMER','SELLER','OWNER','ADMIN')),
 company_id BIGINT REFERENCES company(id),
 CHECK (role NOT IN ('SELLER','OWNER') OR company_id IS NOT NULL)
);
CREATE TABLE category (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE);
CREATE TABLE product (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES company(id), category_id BIGINT NOT NULL REFERENCES category(id),
 name VARCHAR(160) NOT NULL, description VARCHAR(2000) NOT NULL,
 price NUMERIC(14,2) NOT NULL CHECK(price>0), stock INTEGER NOT NULL CHECK(stock>=0),
 active BOOLEAN NOT NULL DEFAULT TRUE, image_url VARCHAR(1000)
);
CREATE INDEX product_catalog ON product(active,category_id,company_id);
CREATE TABLE address (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id BIGINT NOT NULL REFERENCES account(id),
 street VARCHAR(200) NOT NULL, number VARCHAR(30) NOT NULL, complement VARCHAR(120),
 city VARCHAR(120) NOT NULL, state VARCHAR(2) NOT NULL, postal_code VARCHAR(8) NOT NULL
);
CREATE INDEX address_owner ON address(account_id);
CREATE TABLE cart_item (
 account_id BIGINT NOT NULL REFERENCES account(id), product_id BIGINT NOT NULL REFERENCES product(id),
 quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 999), PRIMARY KEY(account_id,product_id)
);
CREATE TABLE coupon (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(40) NOT NULL UNIQUE,
 percentage INTEGER NOT NULL CHECK(percentage BETWEEN 1 AND 100), expires_on DATE NOT NULL,
 usage_limit INTEGER NOT NULL CHECK(usage_limit>0), used INTEGER NOT NULL DEFAULT 0 CHECK(used>=0 AND used<=usage_limit),
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE purchase_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id BIGINT NOT NULL REFERENCES account(id),
 request_key VARCHAR(80) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status VARCHAR(30) NOT NULL DEFAULT 'AWAITING_PAYMENT',
 subtotal NUMERIC(14,2) NOT NULL, discount NUMERIC(14,2) NOT NULL, total NUMERIC(14,2) NOT NULL,
 shipping_address VARCHAR(1000) NOT NULL, coupon_id BIGINT REFERENCES coupon(id),
 UNIQUE(account_id,request_key), CHECK(total>=0)
);
CREATE INDEX order_owner ON purchase_order(account_id,id);
CREATE TABLE order_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES purchase_order(id),
 product_id BIGINT NOT NULL REFERENCES product(id), company_id BIGINT NOT NULL REFERENCES company(id),
 name VARCHAR(160) NOT NULL, quantity INTEGER NOT NULL CHECK(quantity>0), unit_price NUMERIC(14,2) NOT NULL
);
CREATE TABLE payment (
 order_id BIGINT PRIMARY KEY REFERENCES purchase_order(id), method VARCHAR(20) NOT NULL CHECK(method IN ('PIX','CARD','BOLETO')),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
);
CREATE TABLE delivery (
 order_id BIGINT PRIMARY KEY REFERENCES purchase_order(id), status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 carrier VARCHAR(120), tracking_code VARCHAR(120)
);
CREATE TABLE coupon_redemption (
 coupon_id BIGINT NOT NULL REFERENCES coupon(id), account_id BIGINT NOT NULL REFERENCES account(id),
 order_id BIGINT NOT NULL REFERENCES purchase_order(id), PRIMARY KEY(coupon_id,account_id)
);
